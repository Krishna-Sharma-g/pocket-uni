export function searchFaculty(query: string, department?: string): FacultyProfile[] {
  const q = (query || '').trim().toLowerCase();
  const dept = (department || '').trim().toLowerCase();

  return MITS_FACULTY.filter(fac => {
    // 1. Department filter
    if (dept && dept !== 'all') {
      const facDept = (fac.department || '').toLowerCase();
      if (dept === 'cai' || dept === 'ai' || dept.includes('artificial')) {
        if (!facDept.includes('artificial intelligence')) return false;
      } else if (dept === 'cse' || dept.includes('computer')) {
        if (!facDept.includes('computer science')) return false;
      } else if (dept === 'iot' || dept.includes('internet')) {
        if (!facDept.includes('internet of things')) return false;
      } else if (!facDept.includes(dept)) {
        return false;
      }
    }

    // 2. Query filter (case-insensitive partial matching across name, department, designation, research areas, email)
    if (!q) return true;

    const nameMatch = (fac.name || '').toLowerCase().includes(q);
    const desigMatch = (fac.designation || '').toLowerCase().includes(q);
    const deptMatch = (fac.department || '').toLowerCase().includes(q);
    const emailMatch = (fac.emailPublic || '').toLowerCase().includes(q);
    const officeMatch = (fac.officeLocation || '').toLowerCase().includes(q);
    const areasMatch = Array.isArray(fac.researchAreas) && fac.researchAreas.some(area =>
      typeof area === 'string' && area.toLowerCase().includes(q)
    );

    return nameMatch || desigMatch || deptMatch || emailMatch || officeMatch || areasMatch;
  });
}
